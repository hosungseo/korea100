function main() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf8"));
  const existingSlugs = new Set(manifest.map((entry) => entry.slug));
  const existingPriorities = new Set(manifest.map((entry) => entry.priority));
  for (const spec of specs) {
    const outputPath = path.join(DATA_DIR, `${spec.slug}.json`);
    if (!OVERWRITE && fs.existsSync(outputPath)) {
      throw new Error(`${spec.slug}.json already exists; use --overwrite only when intentional`);
    }
    const existingEntryIndex = manifest.findIndex((entry) => entry.slug === spec.slug);
    const priorityConflict = manifest.find((entry) => entry.priority === spec.priority && entry.slug !== spec.slug);
    if (priorityConflict) throw new Error(`manifest already contains priority ${spec.priority} for ${priorityConflict.slug}`);
    if (!OVERWRITE && existingSlugs.has(spec.slug)) throw new Error(`manifest already contains ${spec.slug}`);
    fs.writeFileSync(outputPath, `${JSON.stringify(buildInstitution(spec), null, 2)}\n`);
    const entry = { priority: spec.priority, slug: spec.slug, name: spec.name, type: spec.type, category: spec.category };
    if (existingEntryIndex >= 0) manifest[existingEntryIndex] = entry;
    else manifest.push(entry);
  }
  manifest.sort((a, b) => a.priority - b.priority);
  fs.writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`generated ${specs.length} industry/trade institutions; manifest=${manifest.length}`);
  for (const spec of specs) console.log(`${spec.priority}\t${spec.slug}\t${spec.name}`);
}

main();
